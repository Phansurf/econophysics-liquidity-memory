"""Create explicitly synthetic, reproducible CSV fixtures; no market download."""
from pathlib import Path
from datetime import datetime, timezone, timedelta
import csv
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
folder=ROOT/'data'; folder.mkdir(exist_ok=True)
rng=np.random.default_rng(901)
p=1.0
rows=[]
start=datetime(2020,1,2,9,30,tzinfo=timezone.utc)
for i in range(80):
    stamp=(start+timedelta(minutes=5*i)).isoformat().replace('+00:00','Z')
    rows.append((stamp,p))
    p*=np.exp((.5-.5*p-.5*.15**2)*.1+.15*np.sqrt(.1)*rng.normal())
with (folder/'synthetic_prices.csv').open('w',newline='') as f:
    writer=csv.writer(f);writer.writerow(['timestamp','price']);writer.writerows(rows)
with (folder/'synthetic_quotes.csv').open('w',newline='') as f:
    writer=csv.writer(f);writer.writerow(['timestamp','bid','ask'])
    for stamp,p in rows:
        writer.writerow([stamp,p-.001,p+.001])
    writer.writerow([rows[2][0],1.2,1.1])  # crossed quote
    writer.writerow(['invalid_time',1,1.01])
    writer.writerow([rows[3][0],1,7])       # excessive spread
(folder/'README.md').write_text('''# Synthetic input fixtures\n\nBoth CSV files are generated by `python scripts/make_example_data.py` with seed 901. They are demonstration inputs, not observed market data. Quotes include three deliberately invalid records to test the audit pipeline. Five-minute timestamps are a demonstration clock; simulation dt is 0.1. Corporate actions and an exchange calendar are not supplied.\n''')
print('Generated synthetic CSV fixtures (seed=901).')
